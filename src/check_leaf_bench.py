"""Data and PC reference for the on-board timing of the leaf counters (src/c/leaf_bench.c; exploratory, report 35).

Writes build/leaf_bench/leaf_model.h (one-shot model of subject 0, seed 0, built on the PC as leaf_sweep.py, in
the leafcal.h table format, with the counter bases for k = none / 0 / 10 / 25 / 50) and leaf_rows.h (testing_block0
of subject 0, normalised with the day-1 statistics, Q5.10: the 60 labelled start-up rows = the first trial of each
gesture, and the other 240 rows). Builds leaf_bench.c with bench_pc.c (gcc -O2) and writes its output to
results/leaf_bench_pc.txt: the board must print the same counts and hashes (the timing columns are 0 on the PC).
--export <dir>: also copies the files a CubeMX project needs into <dir> (plain file copy, nothing else).
Usage (in the container): python src/check_leaf_bench.py [--export build/leaf_bench/emg]
"""
import argparse
import os
import shutil
import subprocess
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import check_leafcal_c as CL  # noqa: E402
import leaf_sweep as LS  # noqa: E402
import pipeline as P  # noqa: E402
import selfcal_sweep as S  # noqa: E402
import zscore_sweep as ZW  # noqa: E402

C = os.path.join(P.ROOT, 'src', 'c')
OUT = os.path.join(P.ROOT, 'build', 'leaf_bench')
KS = [('none', None), ('k0', 0), ('k10', 10), ('k25', 25), ('k50', 50)]


def arr(ctype, name, vals, per_line=16):
    vals = [int(v) for v in np.asarray(vals).ravel()]
    lines = [', '.join(str(v) for v in vals[i:i + per_line]) for i in range(0, len(vals), per_line)]
    return f'static const {ctype} {name}[{len(vals)}] = {{\n  ' + ',\n  '.join(lines) + '\n};\n'


def rows2d(ctype, name, X):
    body = ',\n'.join('  {' + ', '.join(str(int(v)) for v in r) + '}' for r in X)
    return f'static const {ctype} {name}[{len(X)}][{X.shape[1]}] = {{\n{body}\n}};\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--export', default=None)
    args = ap.parse_args()
    subject, seed = 0, 0
    np.random.seed(seed * 1000 + subject)
    Xc_raw, yc, blocks, _ = ZW.load('arm_position', subject, 0.0)
    yc = yc.astype(np.int64)
    mu, sd = Xc_raw.mean(0), Xc_raw.std(0)
    mdl = LS.one_shot((Xc_raw - mu) / sd, yc, P.load_pretrain(S.DATASETS['arm_position'][0]))
    X, y = blocks[0]
    y = y.astype(np.int64)
    a, u = LS.anchor_split(y)
    Q = P.quantize((X - mu) / sd)
    os.makedirs(OUT, exist_ok=True)
    (roots, feat, thr, left, right, base50), _ = CL.tables(mdl, 50)
    with open(os.path.join(OUT, 'leaf_model.h'), 'w') as fh:
        fh.write(f'/* Generated by src/check_leaf_bench.py - one-shot model of subject {subject}, seed {seed} (PC), '
                 'leafcal.h tables. */\n#pragma once\n#include <stdint.h>\n')
        fh.write(f'#define LM_N_INTERNAL {len(feat)}\n')
        fh.write(arr('uint32_t', 'lm_roots', roots, 8) + arr('uint8_t', 'lm_feat', feat) + arr('int16_t', 'lm_thr', thr)
                 + arr('uint16_t', 'lm_left', left) + arr('uint16_t', 'lm_right', right))
        for name, k in KS:
            b = np.zeros(LS.N + 1, dtype=np.uint16) if k is None else CL.tables(mdl, k)[0][5]
            fh.write(arr('uint16_t', f'lm_base_{name}', b))
    with open(os.path.join(OUT, 'leaf_rows.h'), 'w') as fh:
        fh.write(f'/* Generated by src/check_leaf_bench.py - subject {subject}, testing_block0, day-1 z-score, Q5.10. */\n'
                 f'#pragma once\n#include <stdint.h>\n#define LR_NA {len(a)}\n#define LR_NU {len(u)}\n')
        fh.write(rows2d('int16_t', 'lr_anchor', Q[a]) + arr('uint8_t', 'lr_anchor_y', y[a]))
        fh.write(rows2d('int16_t', 'lr_use', Q[u]) + arr('uint8_t', 'lr_use_y', y[u]))
    exe = os.path.join(P.ROOT, 'build', 'c', 'leaf_bench_pc')
    os.makedirs(os.path.dirname(exe), exist_ok=True)
    subprocess.run(['gcc', '-O2', '-std=gnu11', '-Wall', f'-I{OUT}', '-o', exe] +
                   [os.path.join(C, f) for f in ('bench_pc.c', 'leaf_bench.c', 'leafcal.c')], check=True)
    out = subprocess.run([exe], check=True, capture_output=True, text=True).stdout
    with open(os.path.join(P.ROOT, 'results', 'leaf_bench_pc.txt'), 'w', newline='\n') as fh:
        fh.write(out.replace('\r\n', '\n'))
    print(out.replace('\r\n', '\n'))
    # the same numbers from the Python prototype's rule, as an independent check of the 'correct' counts
    lab0 = P.leaf_labels(mdl)
    thr_q = LS.thr_q(mdl)
    off = np.concatenate([[0], np.cumsum([len(x) for x in lab0])])[:-1]
    base = np.concatenate(lab0)
    route = lambda Z: np.stack(LS.leaves(mdl, thr_q, Z), axis=1) + off        # noqa: E731
    Ga, Gu = route((X[a] - mu) / sd), route((X[u] - mu) / sd)
    for name, k in KS:
        sel = np.zeros(0, dtype=int) if k is None else np.r_[0:k, LS.N_PRE:LS.N]
        cnt = np.zeros((len(base), LS.K))
        np.add.at(cnt, (Ga[:, sel], y[a][:, None]), 2.0)
        cnt[np.arange(len(base)), base] += 1.0
        lab = np.argmax(cnt, axis=1)
        before = np.array([np.argmax(np.bincount(base[g], minlength=LS.K)) for g in Gu])
        after = np.array([np.argmax(np.bincount(lab[g], minlength=LS.K)) for g in Gu])
        print(f'python {name}: correct {int(np.sum(before == y[u]))} -> {int(np.sum(after == y[u]))} of {len(u)}')
    if args.export:
        os.makedirs(args.export, exist_ok=True)
        for f in ('leaf_bench.c', 'leafcal.c', 'leafcal.h', 'bench.h', 'board.h', 'board_hal.c', 'app_rt.h'):
            shutil.copy2(os.path.join(C, f), args.export)
        for f in ('leaf_model.h', 'leaf_rows.h'):
            shutil.copy2(os.path.join(OUT, f), args.export)
        print('exported to', args.export, sorted(os.listdir(args.export)))


if __name__ == '__main__':
    main()
