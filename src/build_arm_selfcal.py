"""Cross-compile the on-device self-calibration firmware for Cortex-M7 (STM32H743) and measure Flash / RAM.

Links src/c/main_selfcal.c + selfcal.c + tsne.c + kmeans.c + rf_train.c + startup with the one-shot model of
build/d10_n100_i16/rf_model.h (export_c.py: 100 trees, depth 10, int16; subject 0) and the subject-0
calibration set (written here to build/d10_n100_i16/cal_input.h), using the linker script
src/c/stm32h743_axi.ld (.bss in the 512 KB AXI SRAM, stack in DTCM). Same flags as build_arm.py, at -Os and
-O2, as two variants: 'selfcal' (calibration rows replayed into sc_push) and 'full' (-DWITH_FEATURES: raw EMG of
one recorded trial, build/d10_n100_i16/raw_input.h as int16, through features.c into sc_push), plus 'device'
(-DWITH_FEATURES -DWITH_ONESHOT): the one-shot model is built on the MCU (oneshot.c) from the 50 pre-trained
trees (build/oneshot_dev/pre_model.h: depth 10, compacted, Q5.10) and the subject-0 calibration features
(build/oneshot_dev/cal_feat.h, raw float), written to the reserved Flash sector through the board layer
(board_stub.c here: the real Flash driver is the hardware layer), plus 'rt' (main_rt.c: the route-B firmware: serial
protocol, real-time loop, on-device one-shot calibration and self-calibration; no sample data in Flash, board layer
stubbed), and 'board' (the same with the hardware layer board_h7.c + startup_h7.c on the CMSIS headers in src/c/cmsis:
compiled only, not run). All of these are the earlier firmware (-DSC_EMBED=1 -DRT_ADAPT=0: t-SNE, no input
adaptation); 'rt2' / 'board2' are the current one (selfcal.c without t-SNE, tsne.c not linked, one-shot with its own
work area, adapt.c: start-up alignment + class-balanced z-score update). Records arm-none-eabi-size of the ELF (text / data / bss), the worst-case static stack from
-fcallgraph-info=su, and text / data / bss per module (.o). Nothing is run: cycle counts need the board.
Writes results/arm_selfcal_size.csv and results/arm_selfcal_modules.csv.
Usage (in the container): python src/build_arm_selfcal.py
"""
import glob
import os
import re
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import build_arm as B  # noqa: E402
import pipeline as P  # noqa: E402

CSRC, BUILD, OUT = B.CSRC, B.BUILD, B.OUT
MODEL = os.path.join(BUILD, 'd10_n100_i16')
SRCS = ['main_selfcal.c', 'selfcal.c', 'tsne.c', 'kmeans.c', 'rf_train.c', 'startup_h743.c']
OLD = ['-DSC_EMBED=1', '-DRT_ADAPT=0']           # the earlier firmware: t-SNE, no input adaptation
CMSIS = ['-DSTM32H753xx', '-I', os.path.join(CSRC, 'cmsis', 'st'), '-I', os.path.join(CSRC, 'cmsis', 'arm')]
RT = ['main_rt.c', 'rt.c', 'protocol.c', 'decision.c', 'features.c', 'oneshot.c', 'selfcal.c', 'kmeans.c', 'rf_train.c']
VARIANTS = {'selfcal': (OLD, SRCS), 'full': (OLD + ['-DWITH_FEATURES'], SRCS + ['features.c']),
            'device': (OLD + ['-DWITH_FEATURES', '-DWITH_ONESHOT'], SRCS + ['features.c', 'oneshot.c', 'board_stub.c']),
            'rt': (OLD, RT + ['tsne.c', 'board_stub.c', 'startup_h743.c']),
            'board': (OLD + CMSIS, RT + ['tsne.c', 'board_h7.c', 'startup_h7.c']),
            # current firmware (defaults SC_EMBED = 0, RT_ADAPT = 1): no t-SNE module, adapt.c added
            'rt2': ([], RT + ['adapt.c', 'board_stub.c', 'startup_h743.c']),
            'board2': (CMSIS, RT + ['adapt.c', 'board_h7.c', 'startup_h7.c'])}
DEV = os.path.join(BUILD, 'oneshot_dev')
RAW_SCALE = 2e-8            # volts per LSB of the int16 stand-in recording
FLAGS = [f for f in B.FLAGS if f != '-Os']


def write_cal():
    Xc, yc, _ = P.load_subject(B.export_c.SUBJECT)
    q = P.quantize(Xc)
    with open(os.path.join(MODEL, 'cal_input.h'), 'w') as fh:
        fh.write('/* Generated by src/build_arm_selfcal.py - subject 0 calibration set, Q5.10. */\n#pragma once\n'
                 '#include <stdint.h>\n')
        fh.write(f'#define CAL_N {len(q)}\nstatic const int16_t cal_x[{len(q)}][80] = {{\n')
        fh.write(',\n'.join('  {' + ', '.join(str(int(v)) for v in row) + '}' for row in q) + '\n};\n')
        fh.write(f'static const uint8_t cal_y[{len(q)}] = {{' + ', '.join(str(int(v)) for v in yc) + '};\n')
    raw = np.load(os.path.join(P.REPO, 'dataset_arm_position', str(B.export_c.SUBJECT), 'calibration', 'data.npy'))[0]
    r = np.clip(np.round(raw.T / RAW_SCALE), -32768, 32767).astype(np.int16)    # samples x channels
    with open(os.path.join(MODEL, 'raw_input.h'), 'w') as fh:
        fh.write('/* Generated by src/build_arm_selfcal.py - subject 0, calibration trial 0, int16 x RAW_SCALE V. */\n'
                 '#pragma once\n#include <stdint.h>\n')
        fh.write(f'#define RAW_N {len(r)}\n#define RAW_SCALE {RAW_SCALE!r}f\n')
        fh.write(f'static const int16_t raw_x[{len(r)}][8] = {{\n')
        fh.write(',\n'.join('  {' + ', '.join(str(int(v)) for v in row) + '}' for row in r) + '\n};\n')


def write_device():
    """pre_model.h: the 50 pre-trained trees the MCU keeps in Flash; cal_feat.h: raw calibration features."""
    import check_oneshot_c
    os.makedirs(DEV, exist_ok=True)
    _, (roots, feat, thr, left, right) = check_oneshot_c.pre_trees()

    def arr(ctype, name, vals, per_line=16):
        lines = [', '.join(str(int(v)) for v in vals[i:i + per_line]) for i in range(0, len(vals), per_line)]
        return f'static const {ctype} {name}[{len(vals)}] = {{\n  ' + ',\n  '.join(lines) + '\n};\n'
    with open(os.path.join(DEV, 'pre_model.h'), 'w') as fh:
        fh.write('/* Generated by src/build_arm_selfcal.py - 50 pre-trained trees, depth 10, Q5.10 (rf_predict.h format). */\n'
                 '#pragma once\n#include <stdint.h>\n')
        fh.write(f'#define PRE_N_INTERNAL {len(feat)}u\n')
        fh.write(arr('uint32_t', 'pre_roots', roots) + arr('uint8_t', 'pre_feat', feat) + arr('int16_t', 'pre_thr', thr)
                 + arr('uint16_t', 'pre_left', left) + arr('uint16_t', 'pre_right', right))
    raw, y = P.load_folder('arm_position', B.export_c.SUBJECT, 'calibration')
    with open(os.path.join(DEV, 'cal_feat.h'), 'w') as fh:
        fh.write('/* Generated by src/build_arm_selfcal.py - subject 0 calibration features, raw (not normalised). */\n'
                 '#pragma once\n#include <stdint.h>\n')
        fh.write(f'#define CAL_N {len(raw)}\nstatic const float cal_feat[{len(raw)}][80] = {{\n')
        fh.write(',\n'.join('  {' + ', '.join(repr(float(np.float32(v))) + 'f' for v in row) + '}' for row in raw) + '\n};\n')
        fh.write(f'static const uint8_t cal_y[{len(raw)}] = {{' + ', '.join(str(int(v)) for v in y) + '};\n')


def main():
    if not os.path.exists(os.path.join(MODEL, 'rf_model.h')):
        sys.exit('run src/export_c.py first')
    write_cal()
    write_device()
    T = B.Tool('arm-none-eabi-', False)
    print(T.run('gcc', ['--version']).stdout.splitlines()[0])
    rows, mods = [], []
    for (variant, (defs, srcs)), opt in [(v, o) for v in VARIANTS.items() for o in ['-Os', '-O2']]:
        obj = os.path.join(BUILD, 'selfcal_arm', f'{variant}_{opt[1:]}')
        os.makedirs(obj, exist_ok=True)
        for f in glob.glob(os.path.join(obj, '*')):
            os.remove(f)
        common = FLAGS + defs + [opt, '-std=c99', '-Wall', '-fstack-usage', '-fcallgraph-info=su', '-I', DEV, '-I', MODEL,
                                 '-I', CSRC]
        for s in srcs:                                   # per-module sizes
            r = T.run('gcc', common + ['-c', os.path.join(CSRC, s), '-o', os.path.join(obj, s[:-2] + '.o')], cwd=obj)
            if r.returncode != 0:
                sys.exit(r.stderr[-3000:])
            text, data, bss = map(int, T.run('size', [os.path.join(obj, s[:-2] + '.o')]).stdout.splitlines()[1].split()[:3])
            mods.append(dict(variant=variant, opt=opt, module=s, text=text, data=data, bss=bss))
        elf = os.path.join(obj, 'selfcal.elf')
        r = T.run('gcc', common + ['-T', os.path.join(CSRC, 'stm32h743_axi.ld'), '-Wl,-Map=' + elf[:-4] + '.map',
                                   '-o', elf] + [os.path.join(obj, s[:-2] + '.o') for s in srcs] + ['-lm'], cwd=obj)
        if r.returncode != 0:
            sys.exit(r.stderr[-3000:])
        text, data, bss = map(int, T.run('size', [elf]).stdout.splitlines()[1].split()[:3])
        st, path, unknown = B.worst_stack(glob.glob(os.path.join(obj, '*.ci')))
        # rt_rx runs in the UART interrupt (called through a pointer, invisible to the call graph from
        # Reset_Handler) and stacks on top of whatever thread code it interrupts; + 104 B for the exception frame
        # with the FPU context
        # pk_feed calls the packet handler through a pointer too, so the handler chain (on_packet -> samples ->
        # features -> votes -> decision -> tx) is added on top: an upper bound
        isr = 0
        if variant in ('rt', 'board', 'rt2', 'board2'):
            ci = glob.glob(os.path.join(obj, '*.ci'))
            handler = [t for f in ci for t in re.findall(r'title: "([^"]*on_packet)"', open(f).read())][0]
            isr = B.worst_stack(ci, 'rt_rx')[0] + B.worst_stack(ci, handler)[0] + 104
            if variant.startswith('board'):   # board_h7.c: SysTick calls rt_rx through a pointer; USART3 can preempt SysTick
                isr += B.worst_stack(ci, 'SysTick_Handler')[0] + B.worst_stack(ci, 'USART3_IRQHandler')[0] + 104
        syms = T.run('nm', ['-S', '--size-sort', '-t', 'd', elf]).stdout.split('\n')
        big = [l.split() for l in syms if len(l.split()) == 4 and l.split()[2] in 'bBdD']
        big = sorted(big, key=lambda x: -int(x[1]))[:12]
        rows.append(dict(variant=variant, opt=opt, text=text, data=data, bss=bss, flash_KB=(text + data) / 1024,
                         axi_bss_KB=bss / 1024, worst_stack_bytes=st + isr, thread_stack_bytes=st, isr_stack_bytes=isr,
                         stack_path=path,
                         stack_unknown=';'.join(unknown),
                         largest_ram_symbols=';'.join(f'{x[3]}={int(x[1])}' for x in big)))
        print({k: v for k, v in rows[-1].items() if k != 'stack_path'})
    pd.DataFrame(rows).to_csv(os.path.join(OUT, 'arm_selfcal_size.csv'), index=False, float_format='%.2f')
    md = pd.DataFrame(mods)
    md.to_csv(os.path.join(OUT, 'arm_selfcal_modules.csv'), index=False)
    print(md.to_string(index=False))


if __name__ == '__main__':
    main()
