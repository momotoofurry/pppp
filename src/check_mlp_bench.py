"""PC side of the on-board MLP vs LDA timing (src/c/mlp_bench.c, src/c/mlp.c; report 35.39). Exploratory.

1. NinaPro DB6 subject 1 as in nn_compare.py: day-1 rows (D1T1, 960), the next session's cued pass (D1T2 rep 1, 80)
   and probe (reps 7-12, 480), Q5.10 -> build/mlp_bench/mlp_rows.h.
2. The day-1 network (nn_compare.MLP, seed 0, 300 epochs, float64) rounded to float32 -> mlp_weights.h.
3. float64 references of what the board computes: MLP predictions before and after 30 epochs of Adam over the 80
   cued rows in stored order (batch 16; the same update as mlp.c), LDA (db6_sim.RunLDA) day 1 and after the cued
   pass; FNV hashes of the predictions as mlp_bench.c prints them.
4. gcc -O2 build of mlp_bench.c + mlp.c + ldacal.c (a copy with LD_CLASSES 8) + bench_pc.c: its lines must give the
   same counts; the board must give the same lines as the PC build (timings aside; FMA may flip a few).
Writes build/mlp_bench/* and results/mlp_bench_pc.txt, results/mlp_bench_reference.txt.
Usage (in the container, /db6 = D:\\db6_compact): python src/check_mlp_bench.py
"""
import os
import re
import shutil
import subprocess
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import db6_sim as D  # noqa: E402
import nn_compare as NC  # noqa: E402
import pipeline as P  # noqa: E402

C = os.path.join(P.ROOT, 'src', 'c')
B = os.path.join(P.ROOT, 'build', 'mlp_bench')
SUBJECT, EPOCHS, BATCH = 1, NC.EPF, NC.BSF


def fnv(preds):
    h = 2166136261
    for p in preds:
        h = ((h ^ int(p)) * 16777619) & 0xFFFFFFFF
    return h


def arr(name, a, ctype):
    rows = ',\n'.join('  {' + ', '.join(str(int(v)) for v in r) + '}' for r in a)
    return f'static const {ctype} {name}[{a.shape[0]}][{a.shape[1]}] = {{\n{rows}\n}};\n'


def vec(name, a, ctype, fmt=str):
    return f'static const {ctype} {name}[{len(a)}] = {{' + ', '.join(fmt(v) for v in a) + '};\n'


def main():
    os.makedirs(B, exist_ok=True)
    X0, Z0, y0, data = NC.load(SUBJECT)
    S = data[0]
    q = lambda X: np.round(np.asarray(X) * 1024).astype(np.int16)
    I0, Ic, Ip = q(X0), q(S['Xc']), q(S['Xp'])
    assert np.array_equal(I0.astype(np.float64) / 1024, X0)
    with open(os.path.join(B, 'mlp_rows.h'), 'w') as f:
        f.write('/* Generated by src/check_mlp_bench.py: NinaPro DB6 subject 1, day-1 z-score, Q5.10. */\n#pragma once\n'
                '#include <stdint.h>\n')
        f.write(f'#define MR_N1 {len(I0)}\n#define MR_NC {len(Ic)}\n#define MR_NP {len(Ip)}\n')
        f.write(arr('mr_day1', I0, 'int16_t') + vec('mr_day1_y', y0, 'uint8_t'))
        f.write(arr('mr_cue', Ic, 'int16_t') + vec('mr_cue_y', S['yc'], 'uint8_t'))
        f.write(arr('mr_probe', Ip, 'int16_t') + vec('mr_probe_y', S['yp'], 'uint8_t'))
    # day-1 network, float32
    net = NC.MLP(0).fit(X0, y0, NC.EP0, NC.BS0)
    net.W = [w.astype(np.float32).astype(np.float64) for w in net.W]
    net.b = [b.astype(np.float32).astype(np.float64) for b in net.b]
    flat = np.concatenate([np.concatenate([w.ravel(), b]) for w, b in zip(net.W, net.b)]).astype(np.float32)
    with open(os.path.join(B, 'mlp_weights.h'), 'w') as f:
        f.write('/* Generated by src/check_mlp_bench.py: day-1 MLP 80-64-32-8 (nn_compare.MLP seed 0), float32. */\n'
                '#pragma once\n#include "mlp.h"\n')
        f.write(f'#define MW_EPOCHS {EPOCHS}\n#define MW_BATCH {BATCH}\n#define MW_LR {NC.LR:g}f\n#define MW_L2 {NC.L2:g}f\n')
        f.write(f'_Static_assert({len(flat)} == MLP_NPARAM, "parameter count");\n')
        f.write(vec('mw_params', flat, 'float', lambda v: f'{float(v):.9g}f'))
    # references (float64)
    ref = []
    p_mlp0 = np.argmax(net.scores(S['Xp']), 1)
    ft = net.copy()
    ft.W, ft.b = [w.copy() for w in net.W], [b.copy() for b in net.b]
    ft._adam()
    for _ in range(EPOCHS):
        for s in range(0, len(Ic), BATCH):
            ft._step(S['Xc'][s:s + BATCH], S['yc'][s:s + BATCH], NC.LR)
    p_mlp1 = np.argmax(ft.scores(S['Xp']), 1)
    lda = D.RunLDA()
    lda.add(Z0, y0)
    lda.fit()
    p_lda0 = np.argmax(lda.scores(np.asarray(S['Xp'])), 1)   # Xp is already Q5.10: q() inside keeps it
    for c in range(D.K):
        lda.learn(S['Xc'][S['yc'] == c], c, fit=False)
    lda.fit()
    p_lda1 = np.argmax(lda.scores(S['Xp']), 1)
    for name, pr in (('lda day-1', p_lda0), ('lda cue', p_lda1), ('mlp day-1', p_mlp0), ('mlp fine-tuned', p_mlp1)):
        ref.append(f'{name}: correct {int((pr == S["yp"]).sum())} of {len(pr)}, hash {fnv(pr):08x}')
    with open(os.path.join(P.ROOT, 'results', 'mlp_bench_reference.txt'), 'w') as f:
        f.write('# float64 references (src/check_mlp_bench.py)\n' + '\n'.join(ref) + '\n')
    print('\n'.join(ref))
    # C on the PC
    for fsrc in ('mlp.c', 'mlp.h', 'mlp_bench.c', 'ldacal.c', 'bench.h'):   # no -I src/c: its features.h shadows glibc's
        shutil.copy2(os.path.join(C, fsrc), B)
    h = open(os.path.join(C, 'ldacal.h')).read()
    assert '#define LD_CLASSES 6' in h
    open(os.path.join(B, 'ldacal.h'), 'w').write(h.replace('#define LD_CLASSES 6', '#define LD_CLASSES 8   /* mlp_bench copy */'))
    exe = os.path.join(P.ROOT, 'build', 'c', 'mlp_bench_pc')
    subprocess.run(['gcc', '-O2', '-std=gnu11', '-Wall', f'-I{B}', '-o', exe, os.path.join(C, 'bench_pc.c'),
                    os.path.join(B, 'mlp_bench.c'), os.path.join(B, 'mlp.c'), os.path.join(B, 'ldacal.c'), '-lm'],
                   check=True)
    out = subprocess.run([exe], check=True, capture_output=True, text=True).stdout.replace('\r\n', '\n')
    with open(os.path.join(P.ROOT, 'results', 'mlp_bench_pc.txt'), 'w', newline='\n') as f:
        f.write(out)
    print(out)
    for line in ref:
        name = line.split(':')[0]
        m = re.search(rf'^{re.escape(name)}: correct (\d+) of \d+, hash (\w+)', out, re.M)
        rc, rh = re.search(r'correct (\d+) of \d+, hash (\w+)', line).groups()
        print(f'{name:15s} C float32 correct {m.group(1)} hash {m.group(2)} | float64 correct {rc} hash {rh} | '
              f'{"same predictions" if m.group(2) == rh else "differ"}')


if __name__ == '__main__':
    main()
