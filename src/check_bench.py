"""PC reference for the on-board bench (src/c/bench.c + bench_pc.c): build with gcc and run; the board must print
the same one-shot image hash, predictions and votes hash (timing lines are 0 on the PC).
Also writes the bench input build/bench/raw_bench.h: subject 0, testing_block0, the first trial of each of the 6
gestures (raw EMG, 8 x 4000 samples, int16 with one scale chosen so that nothing clips), so that the buffer holds
all classes and sc_end_block runs its K-Means path (a single gesture never clusters and would under-time it).
gcc -O2, and a second build with -ffp-contract=off (no fused multiply-add contraction; arm-none-eabi-gcc may
contract on the Cortex-M7 FPU, so if the board's hashes differ this shows whether that alone can explain it).
Writes results/bench_pc.txt and results/bench_pc_nofma.txt.
Usage (in the container): python src/check_bench.py
"""
import os
import subprocess
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pipeline as P  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
C = os.path.join(ROOT, 'src', 'c')
SRC = ['bench_pc.c', 'bench.c', 'selfcal.c', 'kmeans.c', 'rf_train.c', 'features.c', 'adapt.c', 'oneshot.c']
BENCH = os.path.join(ROOT, 'build', 'bench')
INC = [os.path.join(ROOT, 'build', 'oneshot_dev'), BENCH]


def write_raw(subject=0, block=0):
    d = os.path.join(P.REPO, 'dataset_arm_position', str(subject), f'testing_block{block}')
    data, label = np.load(os.path.join(d, 'data.npy')), np.load(os.path.join(d, 'label.npy'))
    trials = [int(np.flatnonzero(label == c)[0]) for c in range(6)]
    x = np.stack([data[t].T for t in trials])                        # trials x samples x channels
    scale = float(np.abs(x).max()) / 32000.0
    q = np.round(x / scale).astype(np.int16)
    os.makedirs(BENCH, exist_ok=True)
    with open(os.path.join(BENCH, 'raw_bench.h'), 'w') as fh:
        fh.write(f'/* Generated by src/check_bench.py - subject {subject}, testing_block{block}, first trial of each '
                 f'gesture (trials {trials}), int16 x RAW_SCALE V, nothing clipped. */\n#pragma once\n#include <stdint.h>\n')
        fh.write(f'#define RAW_T {len(trials)}\n#define RAW_N {x.shape[1]}\n#define RAW_SCALE {scale!r}f\n')
        fh.write(f'static const uint8_t raw_y[{len(trials)}] = {{{", ".join(str(int(label[t])) for t in trials)}}};\n')
        fh.write(f'static const int16_t raw_x[{len(trials)}][{x.shape[1]}][8] = {{\n')
        for t in range(len(trials)):
            fh.write(' {' + ',\n  '.join('{' + ', '.join(str(v) for v in row) + '}' for row in q[t]) + '},\n')
        fh.write('};\n')
    print(f'raw_bench.h: trials {trials}, labels {[int(label[t]) for t in trials]}, scale {scale:.3g} V/LSB')


def run(name, extra):
    exe = os.path.join(ROOT, 'build', 'c', name)
    os.makedirs(os.path.dirname(exe), exist_ok=True)
    subprocess.run(['gcc', '-O2', '-std=gnu11', '-Wall', '-DSC_EMBED=0', *extra, *[f'-I{d}' for d in INC], '-o', exe,
                    *[os.path.join(C, f) for f in SRC], '-lm'], check=True)
    out = subprocess.run([exe], check=True, capture_output=True, text=True).stdout
    return out


def main():
    write_raw()
    for name, extra, res in [('bench_pc', [], 'bench_pc.txt'), ('bench_pc_nofma', ['-ffp-contract=off'], 'bench_pc_nofma.txt')]:
        out = run(name, extra)
        with open(os.path.join(ROOT, 'results', res), 'w') as fh:
            fh.write(out.replace('\r\n', '\n'))
        print(f'--- {res}')
        print(out.replace('\r\n', '\n'))


if __name__ == '__main__':
    main()
